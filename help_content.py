def _inline(text, link):
    s = _html.escape(text, quote=False)
    s = _re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
    def _a(m):
        href = link(m.group(2)) if m.group(2) in TOPIC_BY_ID else None
        return f'<a href="{href}">{m.group(1)}</a>' if href else m.group(1)
    s = _re.sub(r"\[([^\]]+)\]\(#([a-z0-9_]+)\)", _a, s)
    return s


def body_html(body, link=lambda tid: "#" + tid):
    """內文轉 HTML（只用基本標籤，桌面 QTextBrowser 與瀏覽器都能顯示）。
    規則：開頭「- 」＝項目；開頭「1. 」＝步驟；前面有空白的「- 」＝上一項的子項目；
    「### 」＝小標題；「> 」＝注意框；其他＝段落（連續幾行同一段，以換行分開）。"""
    out, para = [], []
    lst = [None]

    def flush_para():
        if para:
            out.append("<p>" + "<br>".join(_inline(x, link) for x in para) + "</p>")
            para.clear()

    def close_list():
        if lst[0]:
            out.append("</" + lst[0] + ">")
            lst[0] = None

    def open_list(kind):
        if lst[0] != kind:
            close_list()
            out.append("<" + kind + ">")
            lst[0] = kind

    bullet = _re.compile(r"^-\s+")
    number = _re.compile(r"^\d+\.\s+")
    for raw in body.splitlines():
        ln = raw.rstrip()
        st = ln.strip()
        indented = ln[:1] == " "
        if not st:
            flush_para()
            close_list()
        elif st.startswith("### "):
            flush_para(); close_list()
            out.append("<h4>" + _inline(st[4:], link) + "</h4>")
        elif st.startswith("> "):
            flush_para(); close_list()
            out.append('<table class="note" width="100%" cellpadding="8"><tr><td>'
                       + _inline(st[2:], link) + "</td></tr></table>")
        elif indented and lst[0] and out and out[-1].endswith("</li>"):
            sub = bullet.sub("", st)
            out[-1] = out[-1][:-5] + "<br>　• " + _inline(sub, link) + "</li>"
        elif bullet.match(st) and not indented:
            flush_para(); open_list("ul")
            out.append("<li>" + _inline(bullet.sub("", st), link) + "</li>")
        elif number.match(st) and not indented:
            flush_para(); open_list("ol")
            out.append("<li>" + _inline(number.sub("", st), link) + "</li>")
        else:
            close_list()
            para.append(st)
    flush_para()
    close_list()
    return "\n".join(out)


def topic_html(t, link=lambda tid: "#" + tid, anchor=False, with_related=True):
    head = f'<h2{" id=" + chr(34) + t["id"] + chr(34) if anchor else ""}>{_html.escape(t["title"])}</h2>'
    crumb = f'<p class="crumb">{_html.escape(CHAPTER_TITLE.get(t["ch"], ""))}</p>'
    rel = ""
    if with_related and t["rel"]:
        links = "｜".join(f'<a href="{link(r)}">{_html.escape(TOPIC_BY_ID[r]["title"])}</a>'
                         for r in t["rel"] if r in TOPIC_BY_ID and link(r))
        rel = f'<p class="rel"><b>相關：</b>{links}</p>' if links else ""
    return head + crumb + body_html(t["body"], link) + rel


