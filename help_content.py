def norm(s):
    """搜尋比對用：全形→半形、英文小寫、去掉空白與常見標點。"""
    s = _ud.normalize("NFKC", s or "").lower()
    return _re.sub(r"[\s「」『』（）()【】〔〕\[\]、，,。．.：:；;！!？?“”\"'‘’…·・\-—_/|]+", "", s)


def plain_text(body):
    """內文去掉格式符號（搜尋、摘要用）。"""
    s = _re.sub(r"\[([^\]]+)\]\(#[a-z0-9_]+\)", r"\1", body)
    s = s.replace("**", "")
    s = _re.sub(r"^(#{1,6}\s+|>\s?|-\s+|\d+\.\s+)", "", s, flags=_re.M)
    return s


