# 口語問句中不影響意思的字（搜尋時先試原詞，找不到再去掉這些字重試）
_FILLERS = ("請問", "我想要", "我想", "我要", "想要", "要怎麼", "怎麼樣", "怎麼", "如何", "怎樣", "可以",
            "在哪裡", "在哪", "一下", "了", "嗎", "呢", "吧", "啊", "的", "要")


def _strip_fillers(term):
    out = term
    for f in _FILLERS:
        out = out.replace(f, "")
    return out


def _bigrams(s):
    return {s[i:i + 2] for i in range(len(s) - 1)} if len(s) > 1 else {s}


def _term_score(term, ntitle, nkw, lines, nch):
    s = 0
    hit = None
    if term in ntitle:
        s += 100 + (60 if ntitle == term else 0) + (20 if ntitle.startswith(term) else 0)
    if term in nkw:
        s += 50
    hit = next((ln for ln, nl in lines if term in nl), None)
    if hit:
        s += 10
    if term in nch:
        s += 5
    return s, hit


# 口語同義詞：查詢中的左邊詞，另外也用右邊的詞比對（例：「刪掉活動」也找「刪除活動」）
SYNONYMS = {
    "刪掉": "刪除", "刪了": "刪除", "砍掉": "刪除", "移掉": "移除",
    "結束": "完成", "辦完": "完成",
    "退錢": "退費", "退給": "退費", "退回": "退費",
    "弄錯": "打錯", "寫錯": "打錯", "輸入錯": "打錯",
    "登錄": "登入", "帳密": "密碼",
    "復原": "還原", "救回": "還原",
    "開始收": "起算", "不收了": "停用",
    "網站": "網頁",
}


def _expand(term):
    """查詢詞＋同義詞替換後的版本。"""
    out = [term]
    for a, b in SYNONYMS.items():
        if a in term:
            out.append(term.replace(a, b))
    return out


_VOCAB = None


def _vocab():
    """搜尋用詞庫：所有主題的標題與關鍵字（兩個字以上），長的在前。"""
    global _VOCAB
    if _VOCAB is None:
        words = set()
        for t in TOPICS:
            for w in _re.split(r"\s+", t["kw"]) + [t["title"]]:
                w = norm(w)
                if len(w) >= 2:
                    words.add(w)
        _VOCAB = sorted(words, key=len, reverse=True)
    return _VOCAB


def _words_in(sentence):
    """一句話裡認得的詞（長詞優先；被長詞包含的短詞不重複算）。例：「停用的人可以刪掉嗎」→ 停用、刪掉。"""
    found, covered = [], [False] * len(sentence)
    for w in _vocab():
        start = sentence.find(w)
        while start >= 0:
            span = range(start, start + len(w))
            if not all(covered[i] for i in span):
                found.append(w)
                for i in span:
                    covered[i] = True
                break
            start = sentence.find(w, start + 1)
    return found


def search(query, scope=None, limit=None):
    """回傳 [(topic, score, snippet), …]，分數高的在前。
    1. 一般比對：query 用空白分開多個詞，全部都要符合（標題、關鍵字、內文任一處）；
       每個詞先比對原詞，找不到再去掉口語贅字（了、嗎、怎麼、我要…）重試。
    2. 一般比對完全找不到時（常見於打一整句話）：找出句子裡認得的詞（詞庫＝所有標題與關鍵字），
       符合越多、越重要（標題＞關鍵字＞內文）的主題排越前面，只要符合一個詞就列出。
    scope：只搜這些主題 id（網頁用）；None＝全部。"""
    terms = [norm(x) for x in _re.split(r"\s+", (query or "").strip()) if norm(x)]
    if not terms:
        return []
    out = []
    for order, (t, ntitle, nkw, lines, nch) in enumerate(_index()):
        if scope is not None and t["id"] not in scope:
            continue
        score, snippet, ok = 0, "", True
        for term in terms:
            s, hit = 0, None
            for k, variant in enumerate(_expand(term)):
                s, hit = _term_score(variant, ntitle, nkw, lines, nch)
                if s == 0:
                    core = _strip_fillers(variant)
                    if core and core != variant:
                        s, hit = _term_score(core, ntitle, nkw, lines, nch)
                        s = int(s * 0.9)
                if s:
                    s = s if k == 0 else int(s * 0.9)
                    break
            if s == 0:
                ok = False
                break
            if hit and not snippet:
                snippet = hit
            score += s
        if ok:
            out.append((t, score, snippet, order))
    if not out:
        words = []
        for term in terms:
            for variant in _expand(term):
                for v in (variant, _strip_fillers(variant)):       # 原句與去掉贅字後都找（「繳了」本身也是關鍵字）
                    words += [w for w in _words_in(v) if w not in words] if v else []
        idx = _index()
        # 少見的詞比較能分辨主題（例：「網頁登入」中「登入」比「網頁」重要）
        df = {w: sum(1 for (_t, a, b, ls, c) in idx if _term_score(w, a, b, ls, c)[0]) for w in words}
        for order, (t, ntitle, nkw, lines, nch) in enumerate(idx):
            if scope is not None and t["id"] not in scope:
                continue
            score, snippet, n = 0.0, "", 0
            for w in words:
                s, hit = _term_score(w, ntitle, nkw, lines, nch)
                if s:
                    n += 1
                    score += s * (1.0 / (1 + df[w]))
                    if hit and not snippet:
                        snippet = hit
            if n:
                out.append((t, int(score * 100 * n), snippet, order))     # 符合的詞越多、越少見，越前面
    res = []
    for t, sc, sn, order in out:
        if t["ch"] == "term":
            sc -= 3                    # 名詞解釋排在同分的說明主題之後
        if not sn:
            sn = next((ln for ln, _ in _index()[order][3]), "")
        res.append((t, sc, sn, order))
    res.sort(key=lambda x: (-x[1], x[3]))
    res = [(t, sc, sn) for t, sc, sn, _ in res]
    return res[:limit] if limit else res


